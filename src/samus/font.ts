export const CHAR_W = 6;
export const CHAR_H = 8;

const parsed = new Map<string, boolean[][]>();
function glyph(ch: string): boolean[][] {
  let g = parsed.get(ch);
  if (!g) {
    const src = GLYPHS[ch] ?? GLYPHS['?'];
    g = src.split(' ').map((row) => [...row].map((c) => c === '#'));
    parsed.set(ch, g);
  }
  return g;
}

export function hasGlyph(ch: string): boolean {
  return ch in GLYPHS;
}

/** Pixel rows of a glyph (for tests and custom effects). */
export function glyphRows(ch: string): boolean[][] {
  return glyph(ch);
}

const cache = new Map<string, HTMLCanvasElement>();
function glyphCanvas(ch: string, color: string): HTMLCanvasElement {
  const key = ch + '|' + color;
  let c = cache.get(key);
  if (!c) {
    c = document.createElement('canvas');
    c.width = 5;
    c.height = 7;
    const g = c.getContext('2d')!;
    g.fillStyle = color;
    glyph(ch).forEach((row, y) => row.forEach((on, x) => on && g.fillRect(x, y, 1, 1)));
    cache.set(key, c);
  }
  return c;
}

export function textWidth(text: string, scale = 1): number {
  return [...text].length * CHAR_W * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color = '#fff',
  scale = 1,
  shadow?: string,
): void {
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of text) {
    if (ch !== ' ') {
      if (shadow) ctx.drawImage(glyphCanvas(ch, shadow), cx + scale, cy + scale, 5 * scale, 7 * scale);
      ctx.drawImage(glyphCanvas(ch, color), cx, cy, 5 * scale, 7 * scale);
    }
    cx += CHAR_W * scale;
  }
}

export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  text: string,
  cx: number,
  y: number,
  color = '#fff',
  scale = 1,
  shadow?: string,
): void {
  drawText(ctx, text, cx - textWidth(text, scale) / 2 + scale / 2, y, color, scale, shadow);
}

/** Greedy word wrap to a max number of characters per line. */
export function wrapText(text: string, maxChars: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (!line) line = word;
      else if ((line + ' ' + word).length <= maxChars) line += ' ' + word;
      else {
        out.push(line);
        line = word;
      }
      while (line.length > maxChars) {
        out.push(line.slice(0, maxChars));
        line = line.slice(maxChars);
      }
    }
    out.push(line);
  }
  return out;
}
